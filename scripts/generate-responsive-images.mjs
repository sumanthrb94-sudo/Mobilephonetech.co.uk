#!/usr/bin/env node
/**
 * generate-responsive-images — AVIF and WebP renditions of the storefront's
 * own artwork (the home hero campaign and the inspection photo).
 *
 * The originals are 1–1.6 MB PNGs at print-ish sizes. A phone was downloading
 * a 1122px-wide lossless PNG to fill a 390px banner, and it was the largest
 * thing on the page by an order of magnitude. This writes resized, modern-
 * format copies beside them and a manifest the components read to build
 * <picture> sources. The originals stay exactly where they are: they remain
 * the <img> fallback, and saved banner documents in Firestore point at them.
 *
 * Run after adding or replacing one of the files listed below:
 *
 *   npm i --no-save sharp && node scripts/generate-responsive-images.mjs
 *
 * sharp is deliberately not a dependency — nothing at build or run time needs
 * it, and it is a large native install for every CI job to carry.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(root, 'public');
const outDir = path.join(publicDir, 'assets', 'responsive');
const manifestPath = path.join(root, 'src', 'data', 'responsiveImages.ts');

const HERO_SLIDES = ['apple', 'samsung', 'pixel', 'tablets', 'accessories', 'gaming'];

/*
 * Widths per artwork shape, chosen from how large each is actually drawn:
 *  - 3:1 desktop: contained in a 368px-tall canvas, so never wider than
 *    ~1104 CSS px; 2172 is the source and covers 2x screens.
 *  - 4.16:1 wide: only used at >= 1600px, drawn ~1530 CSS px wide.
 *  - 4:5 phone: full viewport width below 1024px.
 */
const JOBS = [
  ...HERO_SLIDES.flatMap(s => [
    { src: `/assets/hero-campaign-${s}-desktop-20261004.png`, widths: [828, 1280, 1600, 2172] },
    { src: `/assets/hero-campaign-${s}-desktop-4x16-20261004.png`, widths: [1600, 1920] },
    { src: `/assets/hero-campaign-${s}-mobile-safe-20261004.png`, widths: [640, 828, 1122] },
  ]),
  { src: '/assets/quality-inspection.png', widths: [480, 768, 1024] },
];

const FORMATS = {
  avif: img => img.avif({ quality: 55, effort: 6 }),
  webp: img => img.webp({ quality: 78, effort: 6 }),
};

fs.mkdirSync(outDir, { recursive: true });

const manifest = {};
for (const job of JOBS) {
  const input = path.join(publicDir, job.src);
  const meta = await sharp(input).metadata();
  const base = path.basename(job.src).replace(/\.[^.]+$/, '');
  const entry = { width: meta.width, height: meta.height };
  for (const [format, encode] of Object.entries(FORMATS)) {
    const candidates = [];
    for (const w of job.widths.filter(w => w <= meta.width)) {
      const name = `${base}-${w}w.${format}`;
      await encode(sharp(input).resize({ width: w })).toFile(path.join(outDir, name));
      candidates.push(`/assets/responsive/${name} ${w}w`);
    }
    entry[format] = candidates.join(', ');
  }
  manifest[job.src] = entry;
  console.log(job.src, `${meta.width}x${meta.height}`);
}

const body = `/**
 * Generated by scripts/generate-responsive-images.mjs — do not edit by hand.
 *
 * Original public path -> intrinsic size and AVIF/WebP srcsets. Anything not
 * listed here (staff uploads, Cloudinary URLs) renders from its original URL.
 */
export interface ResponsiveImage {
  width: number;
  height: number;
  avif: string;
  webp: string;
}

export const RESPONSIVE_IMAGES: Record<string, ResponsiveImage> = ${JSON.stringify(manifest, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")};
`;
fs.writeFileSync(manifestPath, body);
console.log(`wrote ${path.relative(root, manifestPath)}`);
